#!/bin/sh
# Candidates for a map's "Do not read unless asked" and "Lookalikes" rows,
# found from file and folder names and file headers with git only. Read only:
# it changes nothing. The agent shows the list to the user, and only the rows
# the user confirms go into a map. "Hidden links" are never guessed here:
# they come from the user and from finished tasks (the wrap-up skill).
#
# Usage: sh .agents/kit/candidates.sh [folder]   (default: the whole repo)
# Prints one line per candidate: kind<TAB>path<TAB>reason, where kind is
# "skip" or "lookalike". Only paths git tracks, outside SKIP_DIRS.
# Installed by agent_dev_kit; do not edit here.

KIT_LIB="$(cd "$(dirname "$0")" && pwd)/lib.sh"  # before cd: $0 may be relative
ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
  echo "candidates: not inside a git repository"; exit 1; }
cd "$ROOT" || exit 1
SKIP_DIRS="node_modules .venv venv vendor target build dist out bin obj"
LEARNING_DIR="learning_docs"
. "$KIT_LIB" && load_conf
SCOPE=${1:-.}
SCOPE=${SCOPE%/}
[ -e "$SCOPE" ] || { echo "candidates: no such folder: $SCOPE"; exit 2; }
BIG_DATA_LINES=${BIG_DATA_LINES:-2000}
TAB=$(printf '\t')
TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT

# Tracked files in scope, outside skipped folders (the same rules as is_code).
git -c core.quotepath=off ls-files -- "$SCOPE" | awk -v skips="$SKIP_DIRS $LEARNING_DIR" '
  BEGIN { n = split(skips, s, " "); for (i = 1; i <= n; i++) skip[s[i]] = 1 }
  {
    k = split($0, part, "/")
    for (i = 1; i < k; i++) if (part[i] in skip || part[i] ~ /^[._]/ && part[i] != "__snapshots__" && part[i] != "__fixtures__") next
    print
  }' > "$TMP/files"
[ -s "$TMP/files" ] || exit 0

# Every folder that holds a tracked file, one per line.
awk -F/ '{ path = ""; for (i = 1; i < NF; i++) { path = path (i > 1 ? "/" : "") $i; print path } }' "$TMP/files" |
  LC_ALL=C sort -u > "$TMP/dirs"

{
  # Folders whose name says test data, snapshots, generated code or copied code.
  awk -F/ '{
    name = tolower($NF)
    if (name ~ /^(__)?fixtures(__)?$|^testdata$|^test_data$|^__snapshots__$|^snapshots$|^golden$|^goldens$/)
      print "skip\t" $0 "/\ttest data or snapshots"
    else if (name ~ /^generated$|^gen$|^autogen$|^__generated__$/)
      print "skip\t" $0 "/\tgenerated code (by its name)"
    else if (name ~ /^third_party$|^thirdparty$|^external$|^extern$/)
      print "skip\t" $0 "/\tcode copied from elsewhere"
  }' "$TMP/dirs"

  # Files generated by a tool, by name.
  awk '{
    name = $0; sub(/.*\//, "", name)
    if (name ~ /\.min\.(js|css)$|_pb2(_grpc)?\.py$|\.pb\.go$|\.pb\.(cc|h)$|\.g\.dart$|\.generated\.[a-z]+$/)
      print "skip\t" $0 "\tgenerated file (by its name)"
  }' "$TMP/files"

  # Files that say in their first lines that a tool wrote them.
  # Case matters: "do not edit" in plain prose is not a tool's mark.
  git -c core.quotepath=off grep -l -I -E -e 'DO NOT EDIT|@generated|[Aa]uto-?generated|AUTO-?GENERATED' -- "$SCOPE" 2>/dev/null |
    awk 'NR == FNR { tracked[$0] = 1; next } $0 in tracked' "$TMP/files" - |
    while IFS= read -r file; do
      head -5 "$file" 2>/dev/null | grep -qE 'DO NOT EDIT|@generated|[Aa]uto-?generated|AUTO-?GENERATED' &&
        printf 'skip\t%s\tits header says a tool generates it\n' "$file"
    done

  # Big data files: an agent that opens one reads it all.
  grep -iE '\.(csv|tsv|json|jsonl|ndjson|xml|sql)$' "$TMP/files" | while IFS= read -r file; do
    [ -f "$file" ] || continue
    lines=$(wc -l < "$file" | tr -d ' ')
    [ "${lines:-0}" -ge "$BIG_DATA_LINES" ] && printf 'skip\t%s\tdata file, %s lines\n' "$file" "$lines"
  done

  # Folders that look like an old copy, alone or beside the live one.
  awk -F/ '
    function stem(name) {
      name = tolower(name)
      gsub(/[-_.]?(old|legacy|deprecated|backup|bak|archive|archived|unused|new|v[0-9]+|[0-9]+)$/, "", name)
      gsub(/^(old|legacy|deprecated|backup|archive|unused|new)[-_.]?/, "", name)
      return name
    }
    function oldish(name) {
      return tolower(name) ~ /(^|[-_.])(old|legacy|deprecated|backup|bak|archive|archived|unused)([-_.]|$)/
    }
    {
      parent = $0; sub(/\/?[^\/]*$/, "", parent)
      s = stem($NF)
      if (s == "" && oldish($NF)) { print "lookalike\t" $0 "/\tits name says old or unused"; next }
      if (s == "" || s == tolower($NF) && !oldish($NF)) { live[parent "\t" tolower($NF)] = $0; next }
      group[parent "\t" s] = group[parent "\t" s] "\t" $0
      if (oldish($NF)) old[$0] = 1
    }
    END {
      for (key in group) {
        n = split(substr(group[key], 2), members, "\t")
        base = live[key]
        for (i = 1; i <= n; i++) {
          m = members[i]
          if (base != "") print "lookalike\t" m "/\tlooks like " base "/"
          else if (n > 1) { for (j = 1; j <= n; j++) if (j != i) { print "lookalike\t" m "/\tlooks like " members[j] "/"; break } }
          else if (m in old) print "lookalike\t" m "/\tits name says old or unused"
        }
      }
    }' "$TMP/dirs"
} | LC_ALL=C sort -u -t "$TAB" -k2,2 | awk -F '\t' '
  # Drop a candidate inside a folder that is already a skip candidate.
  { for (p in seen) if (index($2, p) == 1 && $2 != p) next; if ($1 == "skip" && $2 ~ /\/$/) seen[$2] = 1; print }'
exit 0
